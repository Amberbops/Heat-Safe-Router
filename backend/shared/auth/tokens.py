"""Strict HS256 access-token and opaque refresh-token helpers."""
from __future__ import annotations

import hashlib
import hmac
import secrets
import time
import uuid

import jwt


ALGORITHM = "HS256"


def hash_otp_code(email: str, otp_code: str, secret: str) -> str:
    """Bind a 6-digit OTP to its normalized email using HMAC-SHA256."""
    msg = f"{email.strip().lower()}:{otp_code.strip()}".encode("utf-8")
    return hmac.new(secret.encode("utf-8"), msg, hashlib.sha256).hexdigest()


def issue_otp_challenge_token(
    *,
    user_id: str,
    email: str,
    purpose: str,
    secret: str,
    issuer: str,
    audience: str,
    ttl_seconds: int = 600,
    now: int | None = None,
) -> str:
    issued_at = int(time.time() if now is None else now)
    payload = {
        "iss": issuer,
        "aud": audience,
        "sub": user_id,
        "email": email,
        "purpose": purpose,
        "iat": issued_at,
        "nbf": issued_at,
        "exp": issued_at + ttl_seconds,
        "jti": str(uuid.uuid4()),
        "token_use": "otp_challenge",
    }
    return jwt.encode(payload, secret, algorithm=ALGORITHM, headers={"typ": "JWT"})


def decode_otp_challenge_token(
    token: str, *, secret: str, issuer: str, audience: str, leeway_seconds: int = 0
) -> dict:
    claims = jwt.decode(
        token,
        secret,
        algorithms=[ALGORITHM],
        issuer=issuer,
        audience=audience,
        leeway=leeway_seconds,
        options={
            "require": ["iss", "aud", "sub", "email", "purpose", "iat", "nbf", "exp", "jti", "token_use"],
            "verify_signature": True,
            "verify_exp": True,
            "verify_iat": True,
            "verify_nbf": True,
        },
    )
    if claims.get("token_use") != "otp_challenge":
        raise jwt.InvalidTokenError("Wrong token type")
    if claims.get("purpose") not in {"register", "login", "amazon"}:
        raise jwt.InvalidTokenError("Invalid challenge purpose")
    return claims


def issue_access_token(
    *, user_id: str, email: str, role: str, session_id: str,
    secret: str, issuer: str, audience: str, ttl_seconds: int = 600,
    now: int | None = None,
) -> str:
    issued_at = int(time.time() if now is None else now)
    payload = {
        "iss": issuer,
        "aud": audience,
        "sub": user_id,
        "email": email,
        "role": role,
        "sid": session_id,
        "iat": issued_at,
        "nbf": issued_at,
        "exp": issued_at + ttl_seconds,
        "jti": str(uuid.uuid4()),
        "token_use": "access",
    }
    return jwt.encode(payload, secret, algorithm=ALGORITHM, headers={"typ": "JWT"})


def decode_access_token(
    token: str, *, secret: str, issuer: str, audience: str,
    leeway_seconds: int = 0,
) -> dict:
    claims = jwt.decode(
        token,
        secret,
        algorithms=[ALGORITHM],
        issuer=issuer,
        audience=audience,
        leeway=leeway_seconds,
        options={
            "require": ["iss", "aud", "sub", "email", "role", "sid", "iat", "nbf", "exp", "jti", "token_use"],
            "verify_signature": True,
            "verify_exp": True,
            "verify_iat": True,
            "verify_nbf": True,
        },
    )
    if claims.get("token_use") != "access":
        raise jwt.InvalidTokenError("Wrong token type")
    if claims.get("role") not in {"user", "admin"}:
        raise jwt.InvalidTokenError("Invalid role")
    return claims


def create_refresh_token(session_id: str | None = None) -> tuple[str, str, str]:
    """Return (opaque token, session_id, SHA-256 hash of its secret portion)."""
    sid = session_id or str(uuid.uuid4())
    secret_part = secrets.token_urlsafe(48)
    token = f"{sid}.{secret_part}"
    return token, sid, hash_refresh_secret(secret_part)


def parse_refresh_token(token: str) -> tuple[str, str]:
    if not isinstance(token, str) or len(token) > 512 or "." not in token:
        raise ValueError("Invalid refresh token")
    session_id, secret_part = token.split(".", 1)
    if not session_id or not secret_part:
        raise ValueError("Invalid refresh token")
    # Session IDs generated by this service are UUIDs.
    uuid.UUID(session_id)
    return session_id, hash_refresh_secret(secret_part)


def hash_refresh_secret(secret_part: str) -> str:
    return hashlib.sha256(secret_part.encode("utf-8")).hexdigest()
